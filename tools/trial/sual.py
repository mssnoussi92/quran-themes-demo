#!/usr/bin/env python3
"""The two verses of each episode of « سؤال صعب » (content/trial/sual.yaml; docs/scripts/sual.md), face to face: the piece
of the verse that raises the question, and the piece of the verse that answers it, written as data for the drawings
(video/src/trial/sualData.ts). Every word comes from the registry (content/sources/quran.yaml, filled from quran.com):
nothing is typed here but the first and the last word of each piece, in their bare form, to find it (as
tools/trial/farq.py does).

  python3 tools/trial/sual.py          # writes video/src/trial/sualData.ts
"""
from __future__ import annotations

import json
from pathlib import Path

import farq

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "video" / "src" / "trial" / "sualData.ts"

# For each episode: the piece of the question's verse, then the piece of the answering verse (a verse, its first and
# last word in bare form).
EPISODES = {
    "dank": [("quran.20.124", "ومن", "ضنكا"), ("quran.6.44", "فتحنا", "شىء")],
    "tayyiba": [("quran.16.97", "فلنحيينه", "طيبة"), ("quran.29.2", "احسب", "يفتنون")],
    "ghafur": [("quran.15.49", "نبئ", "الرحيم"), ("quran.15.50", "وان", "الاليم")],
}


def build(sources: dict) -> dict:
    return {ep: [farq.piece(sources, *p) for p in pieces] for ep, pieces in EPISODES.items()}


def main() -> None:
    data = build(farq.registry())
    for ep, (ask, answer) in data.items():
        print(f"{ep}: {ask['surah']}:{ask['ayah']} « {' '.join(ask['words'])} » / {answer['surah']}:{answer['ayah']} « {' '.join(answer['words'])} »")
    OUT.write_text("// Generated by tools/trial/sual.py from content/sources/quran.yaml: do not edit, run it again.\n"
                   f"export const SUAL = {json.dumps(data, ensure_ascii=False, indent=1)} as const;\n", encoding="utf-8")
    print(OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
