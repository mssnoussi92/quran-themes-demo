#!/usr/bin/env python3
"""The pieces of verses that « معاك 5 ثواني » writes on screen (content/trial/quiz.yaml; docs/scripts/quiz.md): the words
of the question (a word, the start of a verse whose end is to be guessed, a sentence), the choices taken from verses
(the names that close a verse), the end that fills the blank, and the verses face to face of « who said it », written
as data for the drawings (video/src/trial/quizData.ts) with the choices typed in the files (an Egyptian word, never a
verse). Every Quranic word comes from the registry (content/sources/quran.yaml, filled from quran.com); a piece is named
by the positions of its words in the verse (1 is the first; -1 the last), counting only words, not signs of pause, the
same positions as the reciter's word times (content/recitations/), so that a drawing can light a word as it is recited.

  python3 tools/trial/quiz.py          # writes video/src/trial/quizData.ts
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

import farq

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "video" / "src" / "trial" / "quizData.ts"


def piece(sources: dict, ref: dict) -> dict:
    src = sources[ref["verse"]]
    words = [w for w in src["text_ar"].split() if farq.bare(w)]          # a sign of pause alone is not a word
    n = len(words)
    first = ref["from"] if ref["from"] > 0 else n + 1 + ref["from"]
    last = ref["to"] if ref["to"] > 0 else n + 1 + ref["to"]
    if not 1 <= first <= last <= n:
        raise SystemExit(f"error: {ref['verse']} has {n} words: no piece {ref['from']}..{ref['to']}")
    return {"id": ref["verse"], "surah": src["ref"]["surah"], "ayah": src["ref"]["ayah"], "name": src["origin"]["surah_ar"],
            "first": first, "last": last, "words": words[first - 1:last]}


def short(sources: dict, spec: dict) -> dict:
    quiz = spec["quiz"]
    choices = []
    for c in quiz["choices"]:
        made = {"ar": c.get("ar"), "en": c["en"], "right": bool(c.get("right")), "icon": c.get("icon"),
                "note": c.get("note")}        # a wrong choice true elsewhere: its reference, written under it at the answer
        if "verse" in c:
            made["quran"] = piece(sources, c)
        choices.append(made)
    out = {"head": piece(sources, quiz["head"]), "choices": choices, "both": bool(quiz.get("both"))}
    if quiz.get("blank"):
        out["blank"] = piece(sources, quiz["blank"])
    if quiz.get("speakers"):
        out["speakers"] = [{"ar": s["ar"], "en": s["en"], "quran": piece(sources, s)} for s in quiz["speakers"]]
    return out


# The series drawn by the quiz montage: the Page's (`quiz`) and the test page's on Meta (`ma3ak`, 2026-11-18: one
# quiz a day, signed with its name, never on the Page).
SERIES = ("quiz", "ma3ak")


def build(sources: dict) -> dict:
    out = {}
    for name in SERIES:
        series = yaml.safe_load((ROOT / "content" / "trial" / f"{name}.yaml").read_text(encoding="utf-8"))
        for sid in series["shorts"]:
            out[sid] = short(sources, yaml.safe_load((ROOT / "content" / "trial" / f"{sid}.yaml").read_text(encoding="utf-8")))
    return out


def main() -> None:
    data = build(farq.registry())
    for sid, q in data.items():
        h = q["head"]
        print(f"{sid}: {h['surah']}:{h['ayah']} words {h['first']}-{h['last']} « {' '.join(h['words'])} »")
        for c in q["choices"]:
            print(f"   {'✓' if c['right'] else ' '} {c.get('ar') or ' '.join(c['quran']['words'])}")
    OUT.write_text("// Generated by tools/trial/quiz.py from content/trial/<short>.yaml and content/sources/quran.yaml: do not edit, run it again.\n"
                   f"export const QUIZ = {json.dumps(data, ensure_ascii=False, indent=1)} as const;\n", encoding="utf-8")
    print(OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
