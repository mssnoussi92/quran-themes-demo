#!/usr/bin/env python3
"""The words of Al-Ma'un 107:4-5 that the first short of « إزاي أعملها؟ » writes large (content/trial/sahun.yaml;
docs/scripts/sahw.md): « وَيْلٌ » (the first word of 107:4 without its « فَ »), and « عَن » and « صَلَاتِهِمْ » of 107:5,
written as data for the drawings (video/src/trial/sahwData.ts). Every letter comes from the registry
(content/sources/quran.yaml, filled from quran.com); nothing of the verse is typed here.

  python3 tools/trial/sahw.py          # writes video/src/trial/sahwData.ts
"""
from __future__ import annotations

import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "video" / "src" / "trial" / "sahwData.ts"


def words(sources: dict, sid: str) -> list[str]:
    return sources[sid]["text_ar"].split()


def build(sources: dict) -> dict:
    first = words(sources, "quran.107.4")[0]                    # « فَوَيْلٌ »
    if not first.startswith("فَ"):
        raise SystemExit(f"quran.107.4 does not start with « فَ »: {first}")
    w5 = words(sources, "quran.107.5")                          # ٱلَّذِينَ هُمْ عَن صَلَاتِهِمْ سَاهُونَ
    return {"wayl": first[len("فَ"):], "an": w5[2], "salatihim": w5[3], "sahun": w5[4]}


def main() -> None:
    sources = {e["id"]: e for e in yaml.safe_load((ROOT / "content" / "sources" / "quran.yaml").read_text(encoding="utf-8"))}
    data = build(sources)
    print(" · ".join(data.values()))
    OUT.write_text("// Generated by tools/trial/sahw.py from content/sources/quran.yaml: do not edit, run it again.\n"
                   f"export const SAHW_WORDS = {json.dumps(data, ensure_ascii=False)} as const;\n", encoding="utf-8")
    print(OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
