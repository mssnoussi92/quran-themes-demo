#!/usr/bin/env python3
"""The map of a word, for the series « خريطة كلمة » (content/trial/map.yaml; docs/themes.md): where a word of the Quran is
in the 6,236 verses, counted from the Quranic Arabic Corpus and written as data for its drawings
(video/src/trial/mapData.ts). Facts only, each with its rule: how many words of the lemma, in how many verses, in which
form, in which surahs most, the first and the last time in the order of the mushaf. Never two counts set equal.

  curl -sL https://raw.githubusercontent.com/mustafa0x/quran-morphology/master/quran-morphology.txt -o <dir>/morph.txt
  curl -s "https://api.quran.com/api/v4/chapters?language=ar" -o <dir>/chapters.json      # the surahs' names
  python3 tools/trial/wordmap.py --morph <dir>/morph.txt --chapters <dir>/chapters.json
"""
from __future__ import annotations

import argparse
import collections
import json
from pathlib import Path

import count

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "video" / "src" / "trial" / "mapData.ts"

# The episodes: the lemma counted, as the corpus writes it, and the verses the episode marks on the map besides the
# first and the last (the verse of its answer).
WORDS = {
    "qalb": {"lemma": "قَلْب", "marks": [(13, 28)]},
    "nur": {"lemma": "نُور", "marks": [(24, 35)]},
    "sadr": {"lemma": "صَدْر", "marks": [(20, 25)]},
}


def form(features: list[str]) -> str:
    f = set(features)
    return "plural" if {"MP", "FP"} & f else "dual" if {"MD", "FD"} & f else "singular"


def build(words: dict, chapters: dict, lemma: str, marks: list[tuple[int, int]]) -> dict:
    verses = sorted({(s, a) for s, a, _ in words})
    index = {v: i for i, v in enumerate(verses)}
    found = sorted(k for k, w in words.items() if any(x[2] == lemma for x in w))
    each = [[index[k[:2]], form(next(x for x in words[k] if x[2] == lemma)[3]), k[0]] for k in found]   # verse, form, surah
    forms = collections.Counter(f for _, f, _ in each)
    by_surah = collections.Counter(s for s, _, _ in found)
    top = [{"surah": s, "name": chapters[s]["name_arabic"], "n": n} for s, n in by_surah.most_common(3)]
    first, last = found[0], found[-1]
    lit = sorted({index[(s, a)] for s, a, _ in found})
    numbers = {str(len(found)), str(len(lit)), str(forms["plural"]), str(forms["singular"]), str(top[0]["n"])}
    return {
        "lemma": lemma, "total": len(found), "verses": len(lit), "lit": lit, "each": each, "forms": dict(forms), "top": top,
        "first": {"surah": first[0], "ayah": first[1], "index": index[first[:2]], "name": chapters[first[0]]["name_arabic"]},
        "last": {"surah": last[0], "ayah": last[1], "index": index[last[:2]], "name": chapters[last[0]]["name_arabic"]},
        "marks": [{"surah": s, "ayah": a, "index": index[(s, a)], "name": chapters[s]["name_arabic"]} for s, a in marks
                  if (s, a) in {k[:2] for k in found}],
        "particles": {t: count.particles(t, 600, k + 10) for k, t in enumerate(sorted(numbers))},
    }


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--morph", required=True, type=Path)
    p.add_argument("--chapters", required=True, type=Path, help="the answer of quran.com's /chapters")
    p.add_argument("--out", type=Path, default=OUT)
    args = p.parse_args()
    words = count.read(args.morph)
    chapters = {c["id"]: c for c in json.loads(args.chapters.read_text(encoding="utf-8"))["chapters"]}
    data = {"verses": len({(s, a) for s, a, _ in words}), "words": {k: build(words, chapters, w["lemma"], w["marks"]) for k, w in WORDS.items()}}
    assert data["verses"] == 6236
    for k, d in data["words"].items():
        assert len(d["marks"]) == len(WORDS[k]["marks"]), f"{k}: a verse marked has not the word"
        print(f"{k}: {d['total']} words in {d['verses']} verses {d['forms']}; most in {d['top']}; "
              f"first {d['first']['surah']}:{d['first']['ayah']}, last {d['last']['surah']}:{d['last']['ayah']}")
    args.out.write_text("// Generated by tools/trial/wordmap.py from the Quranic Arabic Corpus: do not edit, run it again.\n"
                        f"export const MAP = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))} as const;\n",
                        encoding="utf-8")
    print(args.out.relative_to(ROOT))


if __name__ == "__main__":
    main()
